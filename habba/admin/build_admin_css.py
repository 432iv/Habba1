#!/usr/bin/env python3
"""Generate admin/css/tokens.css from the storefront's own tokens.

The dashboard must look like the storefront WITHOUT editing any storefront
file. This script reads css/habba.css and writes the shared design tokens
(plus the @font-face block) into the admin folder. Re-run it if the
storefront tokens ever change.

    python3 admin/build_admin_css.py
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "css" / "habba.css").read_text()
fonts = (ROOT / "css" / "fonts.css").read_text()
fonts = re.sub(r'url\("\.\./assets/fonts/', 'url("../assets/fonts/', fonts)

roots = re.findall(r":root\s*\{(.*?)\}", src, re.S)
tokens = roots[0]
# later overrides in habba.css (contrast pass)
overrides = re.search(r":root \{\s*(--ink-3: #776E60;.*?)\}", src, re.S)
if overrides:
    tokens = tokens + "\n  " + overrides.group(1).replace(":root {", "").strip()

header = """/* ============================================================================
   HABBA Admin — design tokens
   GENERATED by admin/build_admin_css.py — do not edit by hand.
   Source of truth: css/habba.css (the storefront). Nothing here modifies the
   storefront; the values are copied so both surfaces share one palette.
   ============================================================================ */
"""
out = header + ":root {\n  " + tokens.strip() + "\n}\n\n/* fonts */\n" + fonts
(ROOT / "admin" / "css" / "tokens.css").write_text(out)
print("wrote admin/css/tokens.css", len(out), "bytes")
